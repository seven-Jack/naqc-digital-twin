"""Extract the paired Figure 2b counts from the archived XLS, preserving source cells.

Requires xlrd 2.x only when rebuilding this local snapshot. The application uses
the generated TypeScript file without a Python or workbook dependency. Use
--csv for a portable copy of the same observations.
"""

import argparse
import csv
import hashlib
import io
import json
import math
from pathlib import Path

import xlrd


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "references/library/171yb/yb-senoo-source-fig2.xls"
OUTPUT = ROOT / "src/data/senooReadoutSource.ts"
CSV_OUTPUT = ROOT / "references/library/171yb/derived/senoo-fig2b-readout-pairs.csv"
SOURCE_SHA256 = "81a4c54bd1619b23ce8d60e6f136b2c20912c0f22d8dcef8a053b36a400688f4"

TYPES = """// Generated by scripts/import-senoo-readout.py from the archived Figure 2 XLS.
// Counts retain the source decimals. Each column pairs row 2 (Image 1) with row 3 (Image 2).

export interface SenooReadoutPoint {
  readonly id: string;
  readonly sourceIndex: number;
  readonly sourceColumn: string;
  readonly first: number;
  readonly second: number;
}

export interface SenooReadoutGroup {
  readonly id: 'loss' | 'spin0' | 'spin1';
  readonly label: string;
  readonly sheet: string;
  readonly preparation: string;
  readonly range: string;
  readonly points: readonly SenooReadoutPoint[];
}

export interface SenooReadoutSource {
  readonly schemaVersion: 1;
  readonly source: {
    readonly doi: string;
    readonly url: string;
    readonly title: string;
    readonly figure: string;
    readonly isotope: number;
    readonly state: string;
    readonly tweezerWavelengthNm: number;
    readonly workbook: { readonly file: string; readonly sha256: string };
    readonly locator: string;
    readonly evidenceKind: 'published-figure-source';
    readonly axes: {
      readonly x: { readonly label: string; readonly unit: string };
      readonly y: { readonly label: string; readonly unit: string };
      readonly scale: 'log10';
    };
    readonly conditions: string;
  };
  readonly groups: readonly SenooReadoutGroup[];
}

export const SENOO_READOUT_SOURCE: SenooReadoutSource = """


def extract_snapshot(source: Path) -> dict:
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f"Unexpected source SHA-256 {digest}")
    workbook = xlrd.open_workbook(source)
    groups = []
    for group_id, label, preparation in [
        ("loss", "无原子对照", "未制备原子的对照组"),
        ("spin0", "制备 m₀", "制备 ³P₀ 核自旋态 m₀"),
        ("spin1", "制备 m₁", "制备 ³P₀ 核自旋态 m₁"),
    ]:
        sheet = workbook.sheet_by_name(f"Fig2b_{group_id}")
        if (sheet.nrows, sheet.ncols) != (3, 256) or sheet.cell_value(1, 0) != "X" or sheet.cell_value(2, 0) != "Y":
            raise ValueError(f"Unexpected layout in {sheet.name}")
        points = []
        for column in range(1, 256):
            source_index = sheet.cell_value(0, column)
            if source_index != column - 1:
                raise ValueError(f"Unexpected source index in {sheet.name}, column {column + 1}")
            values = [sheet.cell_value(row, column) for row in (1, 2)]
            if any(sheet.cell_type(row, column) != xlrd.XL_CELL_NUMBER for row in (1, 2)):
                raise ValueError(f"Non-numeric counts in {sheet.name}, column {column + 1}")
            if not all(math.isfinite(value) and value > 0 for value in values):
                raise ValueError(f"Counts outside the source log-axis domain in {sheet.name}, column {column + 1}")
            source_column = xlrd.colname(column)
            points.append({
                "id": f"{sheet.name}:{source_column}",
                "sourceIndex": int(source_index),
                "sourceColumn": source_column,
                "first": values[0],
                "second": values[1],
            })
        groups.append({
            "id": group_id, "label": label, "sheet": sheet.name, "preparation": preparation,
            "range": "B2:IV3", "points": points,
        })
    return {
        "schemaVersion": 1,
        "source": {
            "doi": "10.1038/s41567-026-03258-8",
            "url": "https://doi.org/10.1038/s41567-026-03258-8",
            "title": "High-fidelity entanglement and coherent multi-qubit mapping in an atom array",
            "figure": "2b",
            "isotope": 171,
            "state": "³P₀ m-qubit",
            "tweezerWavelengthNm": 767,
            "workbook": {"file": SOURCE.name, "sha256": digest},
            "locator": "Nature Physics 刊版第 905 页（PDF 第 3 页），图 2b、图注及正文",
            "evidenceKind": "published-figure-source",
            "axes": {
                "x": {"label": "Image 1", "unit": "counts"},
                "y": {"label": "Image 2", "unit": "counts"},
                "scale": "log10",
            },
            "conditions": "¹⁷¹Yb，³P₀ 核自旋 m-qubit，767 nm 光镊。组别按制备条件标注，图示样本各 255 对。源表保留配对计数和序号，逐点时间戳、阈值及相机原图未提供。",
        },
        "groups": groups,
    }


def render_module(snapshot: dict) -> str:
    groups = snapshot["groups"]
    # Keep one paired observation on each line, with all original significant digits.
    lines = [TYPES + "{", '  "schemaVersion": 1,', '  "source": ' + json.dumps(snapshot["source"], ensure_ascii=False, indent=2).replace("\n", "\n  ") + ","]
    lines.append('  "groups": [')
    for index, group in enumerate(groups):
        lines.append("    {")
        for key in ("id", "label", "sheet", "preparation", "range"):
            lines.append(f'      "{key}": {json.dumps(group[key], ensure_ascii=False)},')
        lines.append('      "points": [')
        for point_index, point in enumerate(group["points"]):
            suffix = "," if point_index < len(group["points"]) - 1 else ""
            lines.append("        " + json.dumps(point, ensure_ascii=False) + suffix)
        lines.extend(["      ]", "    }" + ("," if index < len(groups) - 1 else "")])
    lines.extend(["  ]", "};", ""])
    return "\n".join(lines)


def render_csv(snapshot: dict) -> str:
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow([
        "sample_id", "prepared_group", "source_index", "image1_counts", "image2_counts",
        "source_sheet", "image1_cell", "image2_cell",
    ])
    for group in snapshot["groups"]:
        for point in group["points"]:
            column = point["sourceColumn"]
            writer.writerow([
                point["id"], group["id"], point["sourceIndex"], point["first"], point["second"],
                group["sheet"], f"{column}2", f"{column}3",
            ])
    return buffer.getvalue()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--csv", action="store_true", help="write the paired-count CSV instead of the frontend snapshot")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    snapshot = extract_snapshot(args.source)
    output = CSV_OUTPUT if args.csv else OUTPUT
    generated = render_csv(snapshot) if args.csv else render_module(snapshot)
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != generated:
            raise ValueError("The generated source snapshot differs from the archived XLS")
        print("765 paired counts and all source-cell references match the archived XLS")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(generated, encoding="utf-8")
        print(f"Wrote {output.relative_to(ROOT)} with 765 paired observations")


if __name__ == "__main__":
    main()
