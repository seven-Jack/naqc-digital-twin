"""Read the Fig. 2c (right) point estimates and error bars from the local XLS.

Use xlrd 2.x only for extraction. The application loads the resulting static snapshot.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path

import xlrd


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "references/library/171yb/yb-senoo-source-fig2.xls"
OUTPUT = ROOT / "src/data/senooPopulationSource.ts"
SOURCE_HASH = "81a4c54bd1619b23ce8d60e6f136b2c20912c0f22d8dcef8a053b36a400688f4"
HEADERS = ["", "X", "Y", "Y error lower", "Y error upper"]

TYPES = """// Generated by scripts/import-senoo-population.py from the archived Figure 2 XLS.

interface PopulationPoint {
  readonly sourceIndex: number;
  readonly sourceColumn: string;
  readonly timeUs: number;
  readonly population: number;
  readonly lowerError: number;
  readonly upperError: number;
}

interface PopulationTrace {
  readonly id: 'm1' | 'r0';
  readonly label: string;
  readonly sheet: string;
  readonly range: string;
  readonly points: readonly PopulationPoint[];
}

interface PopulationSource {
  readonly schemaVersion: 1;
  readonly source: {
    readonly doi: string;
    readonly figure: string;
    readonly locator: string;
    readonly isotope: number;
    readonly tweezerWavelengthNm: number;
    readonly rydbergDriveWavelengthNm: number;
    readonly conditions: string;
    readonly errorDefinition: string;
    readonly evidenceKind: 'published-figure-source';
    readonly timeUnit: 'µs';
    readonly populationUnit: 'fraction';
    readonly workbook: { readonly file: string; readonly sha256: string };
  };
  readonly traces: readonly PopulationTrace[];
}

export const SENOO_POPULATION_SOURCE: PopulationSource = """


def extract_trace(workbook, sheet_name, trace_id, label):
    sheet = workbook.sheet_by_name(sheet_name)
    if (sheet.nrows, sheet.ncols) != (5, 81) or sheet.col_values(0) != HEADERS:
        raise ValueError(f"Unexpected row layout in {sheet_name}")
    points = []
    for column in range(1, sheet.ncols):
        cell_column = xlrd.colname(column)
        cells = sheet.col_slice(column)
        if any(cell.ctype != xlrd.XL_CELL_NUMBER or not math.isfinite(cell.value) for cell in cells):
            raise ValueError(f"Expected numeric cells in {sheet_name}!{cell_column}1:{cell_column}5")
        index, time, population, lower, upper = [cell.value for cell in cells]
        if index != column - 1 or time < 0 or (points and time <= points[-1]["timeUs"]):
            raise ValueError(f"Unexpected index or time in {sheet_name}!{cell_column}")
        if not (0 <= population <= 1 and lower >= 0 and upper >= 0):
            raise ValueError(f"Invalid population or error magnitude in {sheet_name}!{cell_column}")
        points.append({
            "sourceIndex": int(index), "sourceColumn": cell_column, "timeUs": time,
            "population": population, "lowerError": lower, "upperError": upper,
        })
    return {"id": trace_id, "label": label, "sheet": sheet_name, "range": "B2:CC5", "points": points}


def extract(source):
    original = source.read_bytes()
    digest = hashlib.sha256(original).hexdigest()
    if digest != SOURCE_HASH:
        raise ValueError(f"Unexpected Fig. 2 XLS SHA-256 {digest}")
    workbook = xlrd.open_workbook(file_contents=original)
    traces = [
        extract_trace(workbook, "Fig2c_right_blue", "m1", "m₁"),
        extract_trace(workbook, "Fig2c_right_red", "r0", "r₀"),
    ]
    if [p["timeUs"] for p in traces[0]["points"]] != [p["timeUs"] for p in traces[1]["points"]]:
        raise ValueError("The published traces do not share a sampling grid")
    return {
        "schemaVersion": 1,
        "source": {
            "doi": "10.1038/s41567-026-03258-8",
            "figure": "2c 右图",
            "locator": "刊版第 905 页图 2c 右图及图注。误差定义见刊版图 1 图注。",
            "isotope": 171,
            "tweezerWavelengthNm": 767,
            "rydbergDriveWavelengthNm": 302,
            "conditions": "里德堡比特经 r→m 映射后做带丢失检测的亚稳态自旋测量，同时读取 m₁ 与 r₀。装置使用 767 nm 光镊与 302 nm 里德堡驱动。",
            "errorDefinition": "保留工作簿 Y error lower 和 Y error upper。刊版对布居误差条的一般约定为二项分布 68% 置信区间。",
            "evidenceKind": "published-figure-source",
            "timeUnit": "µs",
            "populationUnit": "fraction",
            "workbook": {"file": SOURCE.name, "sha256": digest},
        },
        "traces": traces,
    }


def render(snapshot):
    prefix = json.dumps({key: value for key, value in snapshot.items() if key != "traces"}, ensure_ascii=False, indent=2)
    parts = [TYPES + prefix.removesuffix("\n}") + ',', '  "traces": [']
    for trace_index, trace in enumerate(snapshot["traces"]):
        header = json.dumps({key: value for key, value in trace.items() if key != "points"}, ensure_ascii=False, indent=2)
        parts.extend(["\n".join("    " + line for line in header.removesuffix("\n}").splitlines()) + ',', '      "points": ['])
        parts.extend("        " + json.dumps(point, ensure_ascii=False) + ("," if index < len(trace["points"]) - 1 else "")
                     for index, point in enumerate(trace["points"]))
        parts.extend(["      ]", "    }" + ("," if trace_index < len(snapshot["traces"]) - 1 else "")])
    parts.extend(["  ]", "};", ""])
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(extract(args.source))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise ValueError("Generated Fig. 2c snapshot differs from the archived worksheet data")
        print("Verified 160 population points and their asymmetric error magnitudes")
    else:
        OUTPUT.write_text(generated)
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
