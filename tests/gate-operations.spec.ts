import { expect, test } from '@playwright/test';

test('从首页逐步定位钟跃迁和里德堡，设备点选、慢放、回拨与整机同步', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('navigation', { name: '整机导航' }).getByRole('link', { name: '门操作', exact: true }).click();
  const gates = page.getByRole('region', { name: '门操作演示' });
  const time = page.getByRole('slider', { name: '演示时间轴' });
  const canvas = page.getByTestId('quantum-scene-canvas');
  await expect(gates).toBeFocused();
  await expect(gates).toHaveAttribute('data-gate', 'CZ');
  await expect(gates).toContainText('序列预览');
  await gates.getByRole('combobox', { name: '门操作播放速度' }).selectOption('0.1');
  await gates.getByRole('button', { name: /钟跃迁转存/ }).click();
  await expect(time).toHaveValue('7425');
  await expect(canvas).toHaveAttribute('data-active-path', 'clock-shelve');
  await gates.getByRole('button', { name: /里德堡激发与阻塞/ }).click();
  await expect(canvas).toHaveAttribute('data-active-path', 'rydberg');
  await expect(gates.getByRole('img')).toHaveAccessibleName(/里德堡激发与阻塞/);
  const basis = gates.getByRole('combobox', { name: '理想输入分量' });
  const mapping = gates.getByLabel('选定分量的理想演化');
  await expect(mapping).toContainText('(|cr⟩ + |rc⟩)/√2');
  const cursor = await time.inputValue();
  await basis.selectOption('00');
  await expect(mapping).toContainText('|00⟩ 保持在基态');
  await expect(time).toHaveValue(cursor);
  await basis.selectOption('11');
  await gates.getByRole('button', { name: '查看门光设备' }).click();
  const panel = page.getByTestId('equipment-panel');
  const device = panel.getByRole('region', { name: '设备门操作' });
  await expect(panel.getByLabel('片段播放速度')).toHaveValue('0.1');
  await panel.locator('button[data-part="probe"]').click();
  await device.getByRole('button', { name: /钟跃迁返回/ }).click();
  await expect(canvas).toHaveAttribute('data-inspection-part', 'clock');
  await expect(canvas).toHaveAttribute('data-active-path', 'clock-return');
  await panel.getByRole('button', { name: '返回整机' }).click();
  await expect(gates).toHaveAttribute('data-phase', 'clock-return');
  await expect(mapping).toContainText('−|11⟩');
  await gates.getByRole('button', { name: '播放此门' }).click();
  await expect(time).toHaveValue('8037');
  await expect(gates.getByRole('button', { name: '播放此门' })).toBeVisible();
  await time.fill('0');
  await expect(gates).not.toHaveAttribute('data-phase', /.+/);
  await page.getByRole('link', { name: '查看第 1 个门 · H（q0）', exact: true }).click();
  await expect(gates).toHaveAttribute('data-phase', 'raman');
  await expect(canvas).toHaveAttribute('data-active-path', 'raman');
  await expect(gates).toBeFocused();
});

test('GHZ 可选第二个原子对，H 门与未执行的门分别显示相应通道和状态', async ({ page }) => {
  await page.goto('/#machine/gates');
  const gates = page.getByRole('region', { name: '门操作演示' });
  const circuits = page.getByRole('group', { name: '量子电路' });
  await circuits.getByRole('button', { name: /GHZ/ }).click();
  await gates.getByLabel('电路中的门').selectOption({ label: '6 · CZ（q1、q2）' });
  await expect(gates).toHaveAttribute('data-phase', 'clock-shelve');
  await expect(page.getByRole('region', { name: '当前阶段设备' })).toContainText('q1、q2');
  await circuits.getByRole('button', { name: /乘积叠加态/ }).click();
  await expect(gates.getByRole('button', { name: /里德堡激发/ })).toHaveCount(0);
  await gates.getByRole('button', { name: /局域拉曼旋转/ }).click();
  await expect(page.getByTestId('quantum-scene-canvas')).toHaveAttribute('data-active-path', 'raman');
  await expect(gates.getByRole('img', { name: /局域拉曼旋转/ })).toContainText('虚能级');
  await expect(gates).toContainText('|1⟩ → (|0⟩ − |1⟩)/√2');
  await page.getByRole('slider', { name: '单阱装载概率' }).fill('0');
  await gates.getByRole('button', { name: '播放此门' }).click();
  await expect(gates).toContainText('本轮已跳过');
  await expect(gates.getByRole('button', { name: '播放此门' })).toBeDisabled();
  await expect(page.getByTestId('quantum-scene-canvas')).not.toHaveAttribute('data-active-path', /.+/);
});
